// Folds the Oracle notes kept in the repo's docs into one bundled file the API can import:
//   docs/oracle/identity/examples/*.json  game identity records (schema in docs/oracle/identity)
//   docs/oracle/games/*.json              Steam study profiles from tools/steam-study
//   docs/oracle/games/_installed.json     the installed-games snapshot
// Run from this folder: `node sync-repo-data.mjs` (build runs it too). `--check` fails if the bundle is stale.
import {readdirSync,readFileSync,writeFileSync,existsSync} from 'node:fs';
const docs=new URL('../../docs/oracle/',import.meta.url),out=new URL('./data/repo-knowledge.json',import.meta.url);
const read=(dir,file)=>JSON.parse(readFileSync(new URL(dir+file,docs),'utf8'));
const list=dir=>existsSync(new URL(dir,docs))?readdirSync(new URL(dir,docs)).filter(f=>f.endsWith('.json')&&!f.startsWith('_')).sort():[];
const slug=s=>String(s).toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');

function collect(){
 const identities=list('identity/examples/').map(f=>{const r=read('identity/examples/',f);return {id:slug(f.replace(/\.json$/,'')),file:'docs/oracle/identity/examples/'+f,...r};});
 const profiles=list('games/').map(f=>{const r=read('games/',f);return {id:slug(f.replace(/\.json$/,'')),file:'docs/oracle/games/'+f,...r};});
 const installed=existsSync(new URL('games/_installed.json',docs))?read('games/','_installed.json'):[];
 return {schema:'oracle.repo-knowledge.v1',note:'Generated by sync-repo-data.mjs from docs/oracle. Edit the docs, not this file.',identities,profiles,installed};
}

{
 if(!existsSync(docs)){console.log('docs/oracle not present; keeping the committed bundle.');process.exit(0);}
 const text=JSON.stringify(collect(),null,1)+'\n';
 if(process.argv.includes('--check')){
  const current=existsSync(out)?readFileSync(out,'utf8'):'';
  if(current!==text){console.error('data/repo-knowledge.json is stale. Run: node sync-repo-data.mjs');process.exit(1);}
  console.log('repo knowledge bundle is current');
 }else{writeFileSync(out,text);const d=JSON.parse(text);console.log(`wrote ${d.identities.length} identity records, ${d.profiles.length} Steam profiles, ${d.installed.length} installed games`);}
}
