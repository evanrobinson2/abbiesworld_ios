export const GLYPH_W = 4;
export const GLYPH_H = 6;

export function textWidth(str, scale = 1) {
  return str.length * GLYPH_W * scale - scale;
}

export function drawText(ctx, str, x, y, color = '#fff', scale = 1, shadow = null) {
  if (shadow) drawText(ctx, str, x + scale, y + scale, shadow, scale);
  ctx.fillStyle = color;
  const s = String(str).toUpperCase();
  for (let i = 0; i < s.length; i++) {
    const g = G[s[i]] || G['?'];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) {
      if (g[r * 3 + c] === '#') ctx.fillRect(x + (i * GLYPH_W + c) * scale, y + r * scale, scale, scale);
    }
  }
}

export function drawTextCentered(ctx, str, cx, y, color, scale = 1, shadow = null) {
  drawText(ctx, str, Math.round(cx - textWidth(str, scale) / 2), y, color, scale, shadow);
}
