"""Write the bundled catalogue for the Ranch Atelier /models section, and copy its files.
usage: python gen_models.py DIST_DIR
/models renders at runtime from a catalogue (see models/README.md for the shape). This writes models/manifest.json,
the fallback catalogue, from the paper warrior prop fits; a database or R2-backed catalogue in the same shape replaces it."""
import sys, os, json, shutil, html
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'cards'))
import importlib.util
spec = importlib.util.spec_from_file_location('cards', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'cards', 'gen_cards_data.py'))
cards = importlib.util.module_from_spec(spec); spec.loader.exec_module(cards)

HERE = os.path.dirname(os.path.abspath(__file__)); S = os.path.join(HERE, '..')
DIST = sys.argv[1]; OUT = os.path.join(DIST, 'models')
esc = html.escape
def pct(x): return f'{round(100 * x)}%'

def record(p):
    n = p['id']; a = cards.summ(n, 'r1_fit_summary.json'); b = cards.summ(n, 'fit_summary.json'); f = b['final']; m = cards.man[n]
    outline = 1 - f['sil']
    status = 'good' if outline >= 0.85 else ('partial' if outline >= 0.75 else 'weak')
    return dict(id=n, name=p['name'], group='Paper warrior · props', subject=p['photo'], orbit=p['orbit'],
                outline=round(outline, 3), status=status, builder=p['builder'], good=p['good'], off=p['off'],
                loss_before=round(a['final']['total'], 3), loss_after=round(f['total'], 3),
                terms=dict(silhouette=f['sil'], edge=f['cham'], ssim=f['ssim'], colour=f['tone'], style=f['style']),
                bars=[('Outline overlap', outline, 'Share of your silhouette and mine that coincide'),
                      ('Edge distance', max(0.0, 1 - f['cham'] * 20), 'How close the outlines run, edge to edge'),
                      ('Structure', 1 - f['ssim'], 'Light and shadow pattern inside the shape (SSIM)'),
                      ('Colour', 1 - f['tone'] * 4, 'Average colour difference from your photo'),
                      ('Paper style', max(0.0, 1 - f['style']), 'Edge statistics: clean folds versus noise')],
                triangles=m['triangles'], size_m=m['size_m'], minutes=round(((a.get('secs') or 0) + (b.get('secs') or 0)) / 60),
                files=dict(ref='ref.jpg', render='render.jpg', overlay='overlay.png', model='model.glb'),
                source=f'tools/paper-warrior/viewer/{n}.glb', made='Blender 5.2 (bpy) in the cloud, procedural Python, no third-party meshes or textures',
                date='2026-10-22')


def entry(r):
    n = r['id']; nm = r['name'].lower(); sz = r['size_m']; t = r['terms']
    base = f'/models/{n}/'
    return dict(id=n, name=r['name'], group=r['group'], subject=r['subject'], status=r['status'], outline=r['outline'],
                orbit=r['orbit'], date=r['date'],
                urls=dict(ref=base + 'ref.jpg', render=base + 'render.jpg', overlay=base + 'overlay.png', glb=base + 'model.glb'),
                scores=[dict(label=k, value=round(v, 3), help=h) for k, v, h in r['bars']],
                loss=dict(before=r['loss_before'], after=r['loss_after'], note='after two fits (lower is better)'),
                good=r['good'], off=r['off'],
                steps=[[f'Built a {nm} generator.', r['builder'] + ' Every piece is generated by Python in Blender, then given paper thickness and flat facets.'],
                       ['Cut out your image.', f'I separated the {nm} from the backdrop so its outline can be scored.'],
                       ['Found your camera.', 'I tried several turns and kept the one whose outline matched best.'],
                       ['Fitted the shape.', '300 small changes to the dimensions, each kept only if the outline got closer.'],
                       ['Fitted light and paper.', '20 rendered rounds tuning light, paper colour and backdrop.'],
                       ['Second pass.', 'Camera held to a sensible range, cream paper and builder fixes, then fitted again.']],
                details=[['Triangles', f"{r['triangles']:,}"], ['Size', f'{sz[0]:.2f} × {sz[1]:.2f} × {sz[2]:.2f} m'],
                         ['Source', f"{r['source']} in abbiesworld_ios"], ['Made with', r['made']],
                         ['Reference', 'Your upload, used only as the scoring target'],
                         ['Compute', f"About {r['minutes']} min across two fits, no AI model calls ($0)"],
                         ['Loss terms', f"silhouette {t['silhouette']:.3f} · edge {t['edge']:.3f} · SSIM {t['ssim']:.3f} · colour {t['colour']:.3f} · style {t['style']:.3f}"],
                         ['Date', '22 Oct 2026']])

os.makedirs(OUT, exist_ok=True)
recs = [record(p) for p in cards.PROPS]
img = os.path.join(S, 'cards', 'img')
for r in recs:
    d = os.path.join(OUT, r['id']); os.makedirs(d, exist_ok=True)
    shutil.copy(os.path.join(img, f"{r['id']}_ref.jpg"), os.path.join(d, 'ref.jpg'))
    shutil.copy(os.path.join(img, f"{r['id']}_render.jpg"), os.path.join(d, 'render.jpg'))
    shutil.copy(os.path.join(img, f"{r['id']}_overlay.png"), os.path.join(d, 'overlay.png'))
    shutil.copy(os.path.join(S, 'site', 'glb', f"{r['id']}.glb"), os.path.join(d, 'model.glb'))
    old = os.path.join(d, 'index.html')
    if os.path.exists(old): os.remove(old)
for f in ('index.html', 'model.html', 'models.css', 'models.js', 'viewer.js', 'README.md'): shutil.copy(os.path.join(HERE, 'site', f), os.path.join(OUT, f))
json.dump(dict(version=1, updated='2026-10-22', models=[entry(r) for r in recs]), open(os.path.join(OUT, 'manifest.json'), 'w'), indent=1, ensure_ascii=False)
print('wrote catalogue of', len(recs), 'models to', OUT)
